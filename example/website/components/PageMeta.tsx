import { useRouter } from "next/router";
import { useConfig } from "nextra-theme-docs";
import React, { useState } from "react";

import scenesData from "./scenes/scenes.json";

export const SITE_URL = "https://rn-carousel.dev";
const SITE_NAME = "React Native Reanimated Carousel";
const SITE_DESCRIPTION =
  "A performant, customizable carousel for React Native, powered by Reanimated and Gesture Handler. Works on iOS, Android and Web.";
const REPO_URL = "https://github.com/dohooo/react-native-reanimated-carousel";
const SCENES_ROUTE = "/Examples/scenes";

const scenes = new Map(scenesData.scenes.map((scene) => [scene.slug, scene]));

/** What every page needs for search engines, link previews and AI agents. */
function usePage() {
  const { asPath } = useRouter();
  const { title, frontMatter } = useConfig();
  const route = asPath.split(/[?#]/)[0].replace(/(.)\/$/, "$1");
  const isHome = route === "/";
  const isNotFound = route === "/404";
  const scene = route.startsWith(`${SCENES_ROUTE}/`)
    ? scenes.get(route.slice(SCENES_ROUTE.length + 1))
    : undefined;
  const image = scene
    ? `/og/scenes/${scene.slug}.jpg`
    : route === SCENES_ROUTE
      ? "/og/scenes.jpg"
      : "/og/default.jpg";

  return {
    route,
    isHome,
    isNotFound,
    scene,
    title: isHome ? SITE_NAME : title,
    // Scene descriptions mark code with backticks, which read as noise in a search snippet.
    description: ((frontMatter.description as string | undefined) || SITE_DESCRIPTION).replace(
      /`/g,
      "",
    ),
    url: isHome ? SITE_URL : `${SITE_URL}${route}`,
    // Every page except the 404 has a Markdown twin, generated by scripts/gen-agent-docs.mjs.
    markdownUrl: isNotFound ? null : isHome ? "/index.md" : `${route}.md`,
    image: `${SITE_URL}${image}`,
  };
}

export function useSeoProps() {
  const page = usePage();
  return {
    title: page.title,
    titleTemplate: "%s – RNRC",
    description: page.description,
    canonical: page.isNotFound ? undefined : page.url,
    noindex: page.isNotFound,
    openGraph: {
      type: page.isHome ? "website" : "article",
      url: page.url,
      siteName: SITE_NAME,
      title: page.title,
      description: page.description,
      images: [{ url: page.image, width: 1200, height: 630, alt: page.title }],
    },
    twitter: { cardType: "summary_large_image", site: "@caspian_1016", handle: "@caspian_1016" },
    additionalLinkTags: page.markdownUrl
      ? [{ rel: "alternate", type: "text/markdown", href: `${SITE_URL}${page.markdownUrl}` }]
      : [],
  };
}

function structuredData(page: ReturnType<typeof usePage>) {
  const library = {
    "@type": "SoftwareSourceCode",
    name: "react-native-reanimated-carousel",
    alternateName: "RNRC",
    description: SITE_DESCRIPTION,
    url: SITE_URL,
    codeRepository: REPO_URL,
    programmingLanguage: "TypeScript",
    runtimePlatform: "React Native",
    license: "https://opensource.org/licenses/MIT",
    author: { "@type": "Person", name: "Caspian", url: "https://github.com/dohooo" },
  };
  if (page.isHome) {
    return [
      {
        "@type": "WebSite",
        "@id": `${SITE_URL}/#website`,
        name: SITE_NAME,
        alternateName: "RNRC",
        url: SITE_URL,
      },
      library,
    ];
  }
  const trail = [
    { name: "RNRC", url: SITE_URL },
    ...(page.scene ? [{ name: "Scenes", url: `${SITE_URL}${SCENES_ROUTE}` }] : []),
    { name: page.title, url: page.url },
  ];
  const nodes: object[] = [
    {
      "@type": "BreadcrumbList",
      itemListElement: trail.map((item, index) => ({
        "@type": "ListItem",
        position: index + 1,
        name: item.name,
        item: item.url,
      })),
    },
  ];
  if (page.scene) {
    nodes.push({
      "@type": "SoftwareSourceCode",
      name: `${page.scene.title} scene`,
      description: page.description,
      url: page.url,
      codeRepository: `${REPO_URL}/tree/main/example/app/app/demos/scenes/${page.scene.slug}`,
      programmingLanguage: "TypeScript",
      runtimePlatform: "React Native",
      isBasedOn: {
        "@type": "SoftwareSourceCode",
        name: "react-native-reanimated-carousel",
        codeRepository: REPO_URL,
      },
    });
  }
  return nodes;
}

/** Rendered inside next/head by the theme, so it may only return head elements. */
export function useHeadTags() {
  const page = usePage();
  const graph = page.isNotFound
    ? null
    : { "@context": "https://schema.org", "@graph": structuredData(page) };
  return (
    <>
      <link rel="icon" href="/favicon.ico" sizes="48x48" />
      <link rel="icon" href="/icon.png" type="image/png" sizes="512x512" />
      <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
      {graph && (
        <script
          key="structured-data"
          type="application/ld+json"
          // biome-ignore lint/security/noDangerouslySetInnerHtml: JSON-LD built from our own data
          dangerouslySetInnerHTML={{ __html: JSON.stringify(graph).replace(/</g, "\\u003c") }}
        />
      )}
    </>
  );
}

const linkClass =
  "nx-text-xs nx-font-medium nx-text-gray-500 hover:nx-text-gray-900 dark:nx-text-gray-400 dark:hover:nx-text-gray-100 contrast-more:nx-text-gray-800 contrast-more:dark:nx-text-gray-50";

/** "Copy page" and "View as Markdown", under the table of contents. */
export function MarkdownLinks() {
  const { markdownUrl } = usePage();
  const [state, setState] = useState<"idle" | "copied" | "failed">("idle");
  if (!markdownUrl) return null;

  const copy = async () => {
    try {
      const response = await fetch(markdownUrl);
      if (!response.ok) throw new Error(String(response.status));
      await navigator.clipboard.writeText(await response.text());
      setState("copied");
    } catch {
      setState("failed");
    }
    setTimeout(() => setState("idle"), 2000);
  };

  return (
    <>
      <button type="button" className={linkClass} onClick={copy}>
        {state === "copied"
          ? "Copied"
          : state === "failed"
            ? "Copy failed"
            : "Copy page as Markdown"}
      </button>
      <a className={linkClass} href={markdownUrl} target="_blank" rel="noreferrer">
        View as Markdown
      </a>
    </>
  );
}
