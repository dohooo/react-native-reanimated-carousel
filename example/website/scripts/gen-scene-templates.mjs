// meta.json text is plain prose with `inline code`; escape what MDX would read as JSX.
function mdxText(text) {
  return text
    .split(/(`[^`]*`)/u)
    .map((part) =>
      part.startsWith("`")
        ? part
        : part.replace(/[{}<>]/gu, (ch) => ({ "{": "\\{", "}": "\\}", "<": "&lt;", ">": "&gt;" })[ch]),
    )
    .join("");
}

// Where each library feature named in a scene's meta.json is documented.
function docsLinkFor(use) {
  if (use.startsWith("ref.")) return "/programmatic-control";
  if (use === "itemAnimation" || use === "relativeProgress") return "/custom-animations";
  return "/props";
}

